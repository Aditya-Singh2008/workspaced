/** Which name table a directory's tags belong to. */
export type TagSpace = "tiff" | "gps" | "interop";

/**
 * A tag's name, or its number when nothing knows it.
 *
 * Hexadecimal for the unknowns, because that is the form every reference and
 * every other metadata tool prints them in — a number someone can paste into a
 * search is a lead, and a decimal one is not.
 */
export function tagName(tag: number, space: TagSpace): string {
  const table =
    space === "gps"
      ? GPS_TAG_NAMES
      : space === "interop"
        ? INTEROP_TAG_NAMES
        : TIFF_TAG_NAMES;
  return table[tag] ?? `0x${tag.toString(16).padStart(4, "0").toUpperCase()}`;
}


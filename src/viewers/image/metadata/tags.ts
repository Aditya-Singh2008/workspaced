/**
 * Tag names, for showing *everything* a file carries rather than a chosen few.
 *
 * `index.ts` builds curated sections — camera, exposure, location — which are
 * the rows most people want and are formatted into sentences rather than raw
 * values. This table backs the other half: a complete listing of every tag in
 * every directory, so nothing in the file is invisible. A metadata panel that
 * silently drops a tag is worse than one that shows it unformatted, because
 * there is no way to tell the difference between "this file does not have that"
 * and "this viewer does not show it".
 *
 * Unknown tags are not dropped either — they are listed by number. Camera
 * vendors put a great deal into private tags, and `0x9C9B` is a lead where a
 * missing row is nothing at all.
 */

